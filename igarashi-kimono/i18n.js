window.applyLang = function(lang){
  document.documentElement.lang = lang === 'en' ? 'en' : 'ja';
  const dict = window.T[lang] || window.T.ja;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.dataset.i18n;
    if (dict[k] != null) el.textContent = dict[k];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const k = el.dataset.i18nHtml;
    if (dict[k] != null) el.innerHTML = dict[k];
  });
  document.querySelectorAll('.lang-tog button').forEach(b => b.classList.toggle('on', b.dataset.lang === lang));
  try { localStorage.setItem('igarashi_lang', lang); } catch(e){}
};

window.initLang = function(){
  const saved = (function(){ try { return localStorage.getItem('igarashi_lang'); } catch(e){ return null; } })();
  const browser = (navigator.language || '').toLowerCase().startsWith('ja') ? 'ja' : 'en';
  window.applyLang(saved || browser || 'ja');
  document.querySelectorAll('.lang-tog button').forEach(b => {
    b.addEventListener('click', () => window.applyLang(b.dataset.lang));
  });
};

document.addEventListener('DOMContentLoaded', window.initLang);
