  if [ -n "$ONLY" ] && [[ "$n" != *"$ONLY"* ]]; then continue; fi
  gen "$n" "${NARR[$n]}"
done

echo ""
for f in *.mp3; do
  dur=$(ffprobe -i "$f" -show_entries format=duration -v quiet -of csv="p=0" 2>/dev/null)
  printf "  %s: %.1fs\n" "$f" "$dur"
done
